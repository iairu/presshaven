"""Loader and filtering helpers for the shared pattern catalogue.

``patterns/patterns.json`` is generated by ``tools/generate_pattern_catalog.py``
from the Lua rules, Suricata rules and the dashboard's Attack Simulation
presets.  The dashboard and the Astro documentation site both consume this
file, so a pattern has one stable ID and one description everywhere.

The catalogue is deliberately Qt-free: it is loaded and tested like any other
core module, and the UI only renders dictionaries from here.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from core.paths import REPO_ROOT

CATALOG_PATH = REPO_ROOT / "patterns" / "patterns.json"


@dataclass(frozen=True)
class PatternCatalog:
    patterns: list[dict]
    by_id: dict[str, dict]
    sources: dict[str, dict]
    kinds: dict[str, str]
    categories: dict[str, str]
    counts: dict
    generated: str = ""
    source_files: list[str] = field(default_factory=list)

    @classmethod
    def load(cls, path: Path | str = CATALOG_PATH) -> "PatternCatalog":
        path = Path(path)
        raw = json.loads(path.read_text(encoding="utf-8"))
        patterns = raw.get("patterns", [])
        return cls(
            patterns=patterns,
            by_id={p["id"]: p for p in patterns},
            sources=raw.get("sources", {}),
            kinds=raw.get("kinds", {}),
            categories=raw.get("categories", {}),
            counts=raw.get("counts", {}),
            generated=raw.get("generated", ""),
            source_files=raw.get("source_files", []),
        )

    # -- filtering ---------------------------------------------------------
    def filter(self, query: str = "", kind: str = "", category: str = "",
               severity: str = "", source: str = "", component: str = "",
               surface: str = "", enabled: bool | None = None) -> list[dict]:
        """Patterns matching every non-empty filter (AND across filters)."""
        needle = query.strip().lower()
        out = []
        for pattern in self.patterns:
            if kind and pattern.get("kind") != kind:
                continue
            if category and pattern.get("category") != category:
                continue
            if severity and pattern.get("severity") != severity:
                continue
            if component and pattern.get("component") != component:
                continue
            if surface and pattern.get("surface") != surface:
                continue
            if enabled is not None and bool(pattern.get("enabled", True)) != enabled:
                continue
            if source and not any(s.get("key") == source for s in pattern.get("sources", [])):
                continue
            if needle and needle not in self.search_text(pattern):
                continue
            out.append(pattern)
        return out

    @staticmethod
    def search_text(pattern: dict) -> str:
        """Lower-cased haystack used by the search box.

        Deliberately includes aliases (CVE/GENERIC IDs), tags, source modules
        and Suricata messages: searching "1000026", "CVE-2024-25600" or
        "upload_rules" should all find the relevant entry.
        """
        parts: list[str] = [
            pattern.get("id", ""),
            pattern.get("name", ""),
            pattern.get("description", ""),
            pattern.get("category", ""),
            pattern.get("category_label", ""),
            pattern.get("kind", ""),
            pattern.get("kind_label", ""),
            pattern.get("severity", ""),
            pattern.get("component", ""),
            pattern.get("plugin", ""),
            pattern.get("surface", ""),
            pattern.get("cve", ""),
            pattern.get("attack_vector", ""),
            pattern.get("trigger", ""),
            pattern.get("notes", ""),
            " ".join(pattern.get("aliases", [])),
            " ".join(pattern.get("wstg", [])),
            " ".join(pattern.get("tags", [])),
        ]
        for source in pattern.get("sources", []):
            parts.extend([source.get("key", ""), source.get("label", ""),
                          source.get("module", ""), source.get("detail", "")])
        for rule in pattern.get("suricata", []):
            parts.extend([str(rule.get("sid", "")), rule.get("message", "")])
        return " ".join(parts).lower()

    # -- option lists ------------------------------------------------------
    def option_values(self, field_name: str) -> list[str]:
        """Distinct values for a filter combo, in catalogue order."""
        seen = []
        for pattern in self.patterns:
            value = pattern.get(field_name, "")
            if value and value not in seen:
                seen.append(value)
        return seen

    def option_labels(self, field_name: str) -> list[tuple[str, str]]:
        """(value, label) pairs for kind/category/severity/component/surface."""
        labels = {
            "kind": self.kinds,
            "category": self.categories,
        }.get(field_name)
        values = self.option_values(field_name)
        if labels:
            return [(v, labels.get(v, v.replace("-", " ").title())) for v in values]
        return [(v, v.replace("-", " ").title()) for v in values]

    def source_options(self) -> list[tuple[str, str]]:
        used = {s.get("key") for p in self.patterns for s in p.get("sources", [])}
        return [(key, meta.get("label", key))
                for key, meta in self.sources.items() if key in used]

    # -- convenience -------------------------------------------------------
    def summary(self) -> dict:
        c = dict(self.counts)
        c.setdefault("total", len(self.patterns))
        c.setdefault("cves", sum(1 for p in self.patterns if p.get("kind") == "cve"))
        c.setdefault("suricata_sids", len({r["sid"] for p in self.patterns
                                          for r in p.get("suricata", [])}))
        return c

    def export_payload(self, patterns: list[dict]) -> dict:
        """A small, self-describing JSON export for the pattern-plugin flow."""
        return {
            "format": "honeypot-ids-pattern-export",
            "version": 1,
            "catalog_generated": self.generated,
            "count": len(patterns),
            # default_enabled is the registry's merge bookkeeping, not pattern data.
            "patterns": [{k: v for k, v in p.items() if k != "default_enabled"}
                         for p in patterns],
        }
